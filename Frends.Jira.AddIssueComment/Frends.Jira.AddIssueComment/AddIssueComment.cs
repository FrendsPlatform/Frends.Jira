using Frends.Jira.AddIssueComment.Definitions;
using Frends.Jira.AddIssueComment.Helpers;
using RestSharp;
using System;
using System.ComponentModel;
using System.Threading;
using System.Threading.Tasks;

namespace Frends.Jira.AddIssueComment;

/// <summary>
/// Jira Task.
/// </summary>
public static class Jira
{
    /// <summary>
    /// Add comment to Jira issue.
    /// [Documentation](https://tasks.frends.com/tasks/frends-tasks/Frends.Jira.AddIssueComment)
    /// </summary>
    /// <param name="input">Input parameters</param>
    /// <param name="connection">Connection parameters.</param>
    /// <param name="options">Optional parameters.</param>
    /// <param name="cancellationToken">Token generated by Frends to stop this Task.</param>
    /// <returns>Object { bool Success, Object Error { string Message, Exception AdditionalInfo } }</returns>
    public static async Task<Result> AddIssueComment([PropertyTab] Input input, [PropertyTab] Connection connection, [PropertyTab] Options options, CancellationToken cancellationToken)
    {
        try
        {
            using var client = new RestClient(connection.JiraBaseUrl);
            client.AddDefaultHeader("Authorization", $"******");

            var request = new RestRequest($"rest/api/latest/issue/{input.IdOrKey}", Method.Get);
            var response = await client.ExecuteAsync(request, cancellationToken);

            if (!response.IsSuccessful)
                throw new Exception($"Error retrieving issue, Status code: {response.StatusCode}, Content: {response.Content}");

            var commentRequest = new RestRequest($"/rest/api/2/issue/{input.IdOrKey}/comment", Method.Post);
            commentRequest.AddHeader("Content-Type", "application/json");
            commentRequest.AddParameter("application/json", $"{{ \"body\": \"{input.Comment}\" }}", ParameterType.RequestBody);

            var updateResponse = await client.ExecuteAsync(commentRequest, cancellationToken);

            if (!updateResponse.IsSuccessful)
                throw new Exception($"Error adding comment, Status code: {updateResponse.StatusCode}, Content: {updateResponse.Content}.");

            return new Result(true);
        }
        catch (Exception ex)
        {
            return ex.Handle(options);
        }
    }
}
